export function buildAgentUserPrompt(symbol: string, stockName: string, today: string): string {
  return `请对股票 ${stockName}（${symbol}）在 ${today} 之后 1-4 周维度的综合影响进行研判。请先搜索相关新闻，再根据需要逐步获取更多信息。`;
}
