/** 去「Ⅲ/Ⅱ/Ⅰ/Ⅳ/Ⅴ…」罗马数字分级后缀（事件侧常带，如「保险Ⅲ」） */
export function stripRomanSuffix(name: string): string {
    return String(name ?? '').trim().replace(/[ⅠⅡⅢⅣⅤⅥⅦⅧⅨⅩ]+$/, '');
}

/**
 * 行业名 → 同族行业名集合（申万一级归组 + 旧名归一）。
 * ① 去罗马数字后缀 ② LEGACY_INDUSTRY_ALIAS 归一 ③ SW_INDUSTRY_MAP 查一级代码
 * ④ 反查同代码下全部行业名。任一步失败 → 返回 `[去后缀后的原始名]`（降级不报错）；空输入 → `[]`。
 */
export function resolveIndustryAliases(name: string): string[] {
    const base = stripRomanSuffix(name);
    if (!base) return [];
    const canonical = LEGACY_INDUSTRY_ALIAS[base] ?? base;
    const code = SW_INDUSTRY_MAP[canonical];
    if (!code) return [base];
    const group: string[] = [];
    for (const [industry, c] of Object.entries(SW_INDUSTRY_MAP)) {
        if (c === code) group.push(industry);
    }
    return group.length > 0 ? group : [base];
}
